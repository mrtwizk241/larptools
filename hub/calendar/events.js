const larpInfo = Object.fromEntries(LARPS.map((l) => [l.id, l]));

function larp(id, start, end, name, extra = {}) {
  const l = larpInfo[id];
  return {
    kind: 'larp',
    larp: id,
    name: `${l.name}: ${name}`,
    start,
    end,
    venue: l.venue,
    city: l.city,
    url: l.events,
    ...extra,
  };
}

