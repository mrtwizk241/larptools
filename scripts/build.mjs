// Builds the whole site into site/ (what Cloudflare Pages serves):
//   site/            the hub page (hub/)
//   site/rustwater/  the Rustwater public build (rustwater/)
//   site/_headers    security and cache headers for every page
// `npm run build`. Pass --no-install to skip `npm ci` in each game folder.
import { execSync } from 'node:child_process';
import { cpSync, existsSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const site = path.join(root, 'site');
const install = !process.argv.includes('--no-install');

/** Each game: its folder, built with `npm run build` into dist-public/. */
const GAMES = ['rustwater'];

function run(command, cwd) {
  console.log(`> ${command} (in ${path.relative(root, cwd) || '.'})`);
  execSync(command, { cwd, stdio: 'inherit' });
}

/**
 * One _headers file for the whole site (Cloudflare Pages reads only the one at the root). The
 * security headers come from the first game's own _headers; its per-path cache rules are repeated
 * under each game's folder, and the hub keeps the rules for `/` and `/index.html`.
 */
function headers() {
  const source = readFileSync(path.join(root, GAMES[0], 'public', '_headers'), 'utf8');
  const blocks = source
    .replace(/\r\n/g, '\n')
    .split(/\n\s*\n/)
    .map((block) => block.split('\n').filter((line) => !line.startsWith('#') && line.trim() !== ''))
    .filter((lines) => lines.length > 0 && lines[0].startsWith('/'));
  const out = ['# Generated by scripts/build.mjs from rustwater/public/_headers. Do not edit.'];
  for (const [first, ...rest] of blocks) {
    if (first === '/*' || first === '/' || first === '/index.html') out.push('', first, ...rest);
  }
  for (const game of GAMES)
    for (const [first, ...rest] of blocks)
      if (first !== '/*') out.push('', `/${game}${first}`, ...rest);
  return `${out.join('\n')}\n`;
}

for (const game of GAMES) {
  const folder = path.join(root, game);
  if (install) run('npm ci --ignore-scripts', folder);
  run('npm run build', folder);
}

rmSync(site, { recursive: true, force: true });
cpSync(path.join(root, 'hub'), site, { recursive: true });
for (const game of GAMES) {
  const built = path.join(root, game, 'dist-public');
  if (!existsSync(path.join(built, 'index.html'))) throw new Error(`${game}: no build in ${built}`);
  cpSync(built, path.join(site, game), { recursive: true });
  rmSync(path.join(site, game, '_headers'), { force: true });
}
writeFileSync(path.join(site, '_headers'), headers());

run(`node scripts/privacy-scan.mjs site`, root);
console.log(`Site built in ${site}.`);
